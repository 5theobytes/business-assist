"""Детерминированный отсекатель «комментарий: …» из ответа пользователя.

Назначение: владелец на каком-то вопросе хочет дать мета-фидбек о самом боте/вопросе
для будущей отладки воркфлоу — например: «комментарий: вопрос непонятный, я уже
отвечала на это». Этот текст НЕ должен попасть в LLM-extractor как «факт о бизнесе»
и НЕ должен искажать диалог. Всё, что после слова «комментарий:» (с любым регистром,
с начала строки) — отрезаем и сохраняем отдельно как `kind="comment"` классификацию.

Применяется ДО classifier.split — чтобы детерминированное правило не зависело от
LLM-промпта.

Голосовой режим (`voice=True`): распознавание речи не вставляет двоеточия. Поэтому
для текста, пришедшего из голосового сообщения, триггер ослаблен — достаточно слова
«комментарий» с пробелом (без двоеточия) в начале сообщения.
"""
from __future__ import annotations

import re

# Текстовый режим: слово "комментарий"/"комментария" + двоеточие, в начале строки.
_COMMENT_TRIGGER_TEXT = re.compile(r"(?:^|\n)\s*комментари[йя]\s*:\s*", re.IGNORECASE)

# Голосовой режим: то же слово, но допускаем пробел вместо двоеточия — STT
# двоеточия не транскрибирует. Якорь начала строки защищает от ложных срабатываний
# на слово «комментарий» в середине предложения.
_COMMENT_TRIGGER_VOICE = re.compile(r"(?:^|\n)\s*комментари[йя]\s+", re.IGNORECASE)


def parse_comment(text: str, *, voice: bool = False) -> tuple[str, str | None]:
    """Разбить ввод пользователя на (ответ, комментарий или None).

    Если в тексте есть «комментарий: …» с начала строки — всё после двоеточия уходит
    в комментарий, остальное — в ответ. В голосовом режиме (`voice=True`) триггер
    ослаблен: «комментарий » без двоеточия тоже срабатывает, потому что STT не
    вставляет двоеточия.
    """
    if not text:
        return "", None
    # Сначала строгий триггер с двоеточием — работает для обоих режимов.
    match = _COMMENT_TRIGGER_TEXT.search(text)
    if not match and voice:
        match = _COMMENT_TRIGGER_VOICE.search(text)
    if not match:
        return text.strip(), None
    answer = text[: match.start()].strip()
    comment = text[match.end():].strip()
    return answer, (comment or None)
